#!/usr/bin/env python3
"""ILLEGANT business discovery: unit-economics model (6 Nov 2026).

Reproducible: `python3 tools/research/unit_economics.py > docs/research/02-unit-economics.md`

Every input is labelled:
  [S]  stated by a cited source (see docs/research/00-sources-log.md), not audited
  [E]  my estimate / assumption, to be replaced by real numbers from the supplier dashboard
Nothing here is a verified supplier quote. Change the inputs, rerun, and the tables update.
"""

VAT = 0.24                # [S] Greek standard VAT rate (clothing, prints, accessories)
EUR_PER_USD = 0.92        # [E] conversion for the USD-quoted ad benchmark
CPC_EUR = 0.85 * EUR_PER_USD   # [S][?] Meta Greece CPC projection 2026 (one source)
CVR = {"pessimistic": 0.010, "base": 0.015, "optimistic": 0.025}  # [E] cold-traffic conversion rate
PROC_PCT, PROC_FIX = 0.029, 0.30   # [E] card processor fee (Shopify Payments / Stripe-like)
THIRD_PARTY_SURCHARGE = 0.02       # [S] Shopify Basic surcharge if Shopify Payments is NOT available
FIXED_MONTHLY = 29 + 2             # [S][?] Shopify Basic ~EUR 29 + [E] domain ~EUR 2/month

# name, retail price incl. VAT [E], product cost (low, base, high), shipping cost (low, base, high),
# expected return/remake rate [E], cost basis note
CANDIDATES = [
    ("Personalised pet portrait print 30x40 (Gelato, made in GR)", 39,
     (7, 10, 14), (4, 5, 7), 0.03,
     "[E] only 13x18 = EUR 5.68 [S] is published; 30x40 not found"),
    ("Personalised pet portrait, framed 30x40 (Gelato)", 79,
     (25, 32, 40), (6, 8, 10), 0.05,
     "[E] framed price not found"),
    ("Design print 50x70, non-personalised (Gelato)", 45,
     (12, 16, 20), (5, 6, 8), 0.10,
     "[E] 50x70 price not found; withdrawal right applies"),
    ("Personalised pet bandana (Printify EU provider)", 22,
     (7.60, 9, 12.40), (4, 5, 6), 0.05,
     "[S] EUR 7.60-12.40 listing 'from' price; shipping [E]"),
    ("Personalised velveteen pet blanket (Printify)", 45,
     (11.52, 14, 18), (5, 6, 8), 0.05,
     "[S] from EUR 11.52 (size unknown); shipping [E]"),
    ("POD premium tee, embroidered logo (Printful EU)", 45,
     (14, 17, 20), (4.79, 5.5, 7), 0.30,
     "[E] tee cost not verified; shipping EUR 4.79 [S][?] one blog; returns ~30% [S][?]"),
]

def net_of_vat(p): return p / (1 + VAT)

def unit(price, cost, ship, ret, surcharge):
    rev = net_of_vat(price)
    fees = price * (PROC_PCT + surcharge) + PROC_FIX   # fees are charged on the gross amount
    # returns/remakes: lost product + shipping on that share of orders (customer refunded, item rarely resaleable)
    ret_cost = ret * (cost + ship)
    contrib = rev - cost - ship - fees - ret_cost
    return rev, fees, ret_cost, contrib

def fmt(x): return f"{x:,.2f}"

print("# Unit economics: candidate products (generated)\n")
print("Generated by `tools/research/unit_economics.py`. **No input below is a verified supplier quote.**")
print("[S] = stated by a source in `00-sources-log.md`; [E] = estimate. Replace the [E] values with the numbers")
print("shown in the free Gelato / Printify / Printful dashboards before any decision.\n")
print(f"Assumptions: VAT {VAT:.0%} [S] · processor {PROC_PCT:.1%} + EUR {PROC_FIX:.2f} [E] · "
      f"Shopify third-party surcharge {THIRD_PARTY_SURCHARGE:.0%} [S] (only if Shopify Payments is unavailable) · "
      f"Meta CPC EUR {CPC_EUR:.2f} [S][?] · conversion {', '.join(f'{k} {v:.1%}' for k,v in CVR.items())} [E] · "
      f"fixed costs EUR {FIXED_MONTHLY}/month [S][?]+[E].\n")

for surcharge, label in ((0.0, "A. Shopify Payments available"), (THIRD_PARTY_SURCHARGE, "B. Third-party gateway (+2%)")):
    print(f"## {label}\n")
    print("| Product | Price incl. VAT | Revenue ex VAT | Product (base) | Shipping (base) | Fees | Returns | **Contribution before ads (low / base / high cost)** | Margin % (base) | Organic orders/month to cover fixed costs |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for name, price, cost, ship, ret, note in CANDIDATES:
        res = [unit(price, cost[i], ship[i], ret, surcharge) for i in range(3)]
        rev, fees, retc, cb = res[1]
        be = FIXED_MONTHLY / cb if cb > 0 else float("inf")
        print(f"| {name} | {price} [E] | {fmt(rev)} | {fmt(cost[1])} | {fmt(ship[1])} | {fmt(fees)} | {fmt(retc)} | "
              f"{fmt(res[0][3])} / **{fmt(cb)}** / {fmt(res[2][3])} | {cb/rev:.0%} | {be:.1f} |")
    print()

print("## Paid acquisition test (scenario A, base cost)\n")
print("CAC = CPC / conversion rate. Profit per **first** order = contribution before ads − CAC.\n")
print("| Product | Contribution before ads | " + " | ".join(f"CAC {k} (EUR {CPC_EUR/v:.0f})" for k, v in CVR.items()) + " | Max CAC that breaks even |")
print("|---|---|" + "---|" * len(CVR) + "---|")
for name, price, cost, ship, ret, note in CANDIDATES:
    cb = unit(price, cost[1], ship[1], ret, 0.0)[3]
    cells = " | ".join(fmt(cb - CPC_EUR / v) for v in CVR.values())
    print(f"| {name} | {fmt(cb)} | {cells} | {fmt(cb)} |")
print()

print("## Cost basis per product\n")
for name, price, cost, ship, ret, note in CANDIDATES:
    print(f"- **{name}**: product {cost} / shipping {ship} (low, base, high); return/remake rate {ret:.0%} [E]. {note}")
print()

print("## 90-day scenario: recommended product mix (organic-first)\n")
print("Mix [E]: 70% unframed portrait (EUR 39), 30% framed (EUR 79); base costs; Shopify Payments; 0 ad spend")
print("except an optional EUR 100 test. Orders/month are **assumptions**, not forecasts.\n")
print("| Orders / month [E] | Revenue ex VAT | Contribution | Fixed costs | Optional ad test (per month) | Monthly result |")
print("|---|---|---|---|---|---|")
p1 = unit(39, 10, 5, 0.03, 0.0); p2 = unit(79, 32, 8, 0.05, 0.0)
for n in (5, 15, 30, 60):
    rev = n * (0.7 * p1[0] + 0.3 * p2[0]); cb = n * (0.7 * p1[3] + 0.3 * p2[3])
    ads = 100 if n >= 15 else 0
    print(f"| {n} | {fmt(rev)} | {fmt(cb)} | {FIXED_MONTHLY} | {ads} | **{fmt(cb - FIXED_MONTHLY - ads)}** |")
print("\nNot included: the founder's time (design/proofing ~15–30 min per personalised order [E]), accountant fees,")
print("business registration costs and EFKA contributions once a business exists. These can exceed the contribution")
print("at low volume and must be quoted by the accountant.")
